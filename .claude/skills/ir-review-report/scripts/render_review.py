#!/usr/bin/env python3
"""Render the final review Markdown from validated JSON artifacts.

The review body is intentionally generated by code. This prevents the final
Markdown from drifting away from the verified issue list, checklist results, and
summary counts.

Usage:
    python render_review.py --issues issues_normalized.json \
        --summary summary.json --results checklist_results.json \
        --claim-assessments claim_assessments.json \
        --out final_review.md [--skill-dir <skill-dir>] \
        [--mode customer|reporter|both|auto] \
        [--mechanical mechanical_checks.json] [--metadata input_metadata.json]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import review_io
from check_issues import (  # noqa: E402
    issue_class,
    issue_location,
    issue_quotes,
    result_id,
    to_markdown,
)

FIXED_HEADINGS = [
    "# インシデント調査報告書レビュー結果",
    "## 1. レビュー対象",
    "## 2. 総合評価",
    "## 3. 重大な指摘事項",
    "## 4. 主要結論の妥当性",
    "## 5. 推奨対策の妥当性",
    "## 6. 形式・チェックリスト上の指摘",
    "## 7. 機械チェック・証拠IDの検査結果",
    "## 8. 外部確認事項",
    "## 9. 任意改善事項",
    "## 10. AIレビューの制約",
    "## 付録A. チェックリスト全項目結果",
]


def load_json(path: Path | None, default: object) -> object:
    if path is None:
        return default
    data, error = review_io.load_json_safe(path)
    if error is not None:
        # Without this, a malformed input here (any of --issues/--summary/
        # --results/--metadata/--claim-assessments/--mechanical) raised an
        # uncaught json.JSONDecodeError — a raw traceback with no indication
        # of which of the 6 files was actually broken.
        print(f"error: {path} を読み込めません — {error}", file=sys.stderr)
        raise SystemExit(2)
    return data


def load_checklist_items(skill_dir: Path, mode: str) -> list[dict]:
    parser = skill_dir / "scripts" / "parse_checklists.py"
    proc = subprocess.run(
        [
            sys.executable,
            str(parser),
            "--skill-dir",
            str(skill_dir),
            "--mode",
            mode,
        ],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr)
        raise SystemExit(2)
    return json.loads(proc.stdout)["items"]


def infer_mode(results: list[dict], requested: str) -> str:
    if requested != "auto":
        return requested
    ids = {
        result_id(r) for r in results
        if isinstance(r, dict) and result_id(r)
    }
    has_customer = any(str(i).startswith("CUS-") for i in ids)
    has_reporter = any(str(i).startswith("REP-") for i in ids)
    if has_customer and not has_reporter:
        return "customer"
    if has_reporter and not has_customer:
        return "reporter"
    return "both"


def result_rationale(result: dict) -> str:
    return str(result.get("rationale") or result.get("finding") or "").strip()


def fmt_issue(issue: dict) -> str:
    parts = [
        f"- `{issue['issue_id']}` [{issue_class(issue)} / {issue['severity']}] "
        f"{issue.get('category', '')}",
        f"  - 位置: {issue_location(issue) or '未設定'}",
        f"  - 理由: {issue.get('reason', '')}",
        f"  - 修正案: {issue.get('suggested_revision', '')}",
    ]
    cids = issue.get("checklist_ids") or []
    if cids:
        parts.append(f"  - 関連チェック項目: {', '.join(cids)}")
    assessment_ids = issue.get("assessment_ids") or []
    if assessment_ids:
        parts.append(f"  - 関連評価: {', '.join(assessment_ids)}")
    absence_ids = issue.get("absence_check_ids") or []
    if absence_ids:
        parts.append(f"  - 未記載確認: {', '.join(absence_ids)}")
    span_ids = issue.get("source_span_ids") or []
    if span_ids:
        parts.append(f"  - 原文span: {', '.join(span_ids)}")
    quotes = issue_quotes(issue)
    if quotes:
        parts.append("  - 原文引用:")
        for q in quotes:
            text = str(q.get("text", "")).replace("\n", " ").strip()
            parts.append(f"    - {q.get('location', '')}: 「{text}」")
    return "\n".join(parts)


def section_or_empty(issues: list[dict], classes: set[str],
                     severities: set[str] | None = None) -> str:
    selected = [
        i for i in issues
        if issue_class(i) in classes
        and (severities is None or i.get("severity") in severities)
    ]
    if not selected:
        return "該当する指摘はありません。"
    return "\n\n".join(fmt_issue(i) for i in selected)


def _limitation_text(a: dict) -> str:
    limitations = a.get("limitation_assessment")
    if limitations is None:
        limitations = a.get("limitations")
    if isinstance(limitations, list):
        limitations = "; ".join(str(x) for x in limitations)
    return str(limitations or "").replace("\n", " ").strip()


def _assessment_reason(a: dict) -> str:
    """One evaluation text. Files written before the schema was slimmed down
    still carry separate evidence / logic / confidence fields; they are folded
    into the same cell so nothing is lost when re-rendering. (Limitations keep
    their own column.)"""
    parts = [
        str(a.get("review_rationale") or a.get("reason") or a.get("assessment_reason") or ""),
        *(
            f"{label}: {a[key]}"
            for label, key in (
                ("根拠", "evidence_assessment"), ("論理", "logic_assessment"),
                ("確度", "confidence_assessment"),
            )
            if a.get(key)
        ),
    ]
    return " / ".join(p.strip() for p in parts if p and p.strip()).replace("\n", " ")


def render_assessments(data: object) -> str:
    assessments = (data or {}).get("claim_assessments", data if isinstance(data, list) else [])
    if not assessments:
        return "主要結論の内容評価がありません。`claim_assessments.json` を作成して再生成してください。"
    # The 限界 column appears only when some assessment actually has limitations;
    # otherwise it would be a column of "-".
    show_limits = any(_limitation_text(a) for a in assessments)
    header = "| ID | 主要結論 | 報告書上の確度 | 評価 | 評価理由 |" + (" 限界 |" if show_limits else "")
    lines = [header, "|---|---|---|---|---|" + ("---|" if show_limits else "")]
    for a in assessments:
        aid = a.get("assessment_id") or a.get("id") or "-"
        conclusion = str(
            a.get("stated_text")
            or a.get("conclusion_text")
            or a.get("conclusion")
            or a.get("claim")
            or ""
        ).replace("\n", " ")
        confidence = a.get("stated_confidence") or "-"
        verdict = a.get("review_verdict") or "-"
        reason = _assessment_reason(a) or str(a.get("support_summary") or "-")
        row = f"| {aid} | {conclusion} | {confidence} | {verdict} | {reason} |"
        if show_limits:
            row += f" {_limitation_text(a) or '-'} |"
        lines.append(row)
    return "\n".join(lines)


def render_inventory(data: object) -> str:
    inventory = (data or {}).get("conclusion_inventory", [])
    if not inventory:
        return "主要結論の棚卸しがありません。`claim_assessments.json` の `conclusion_inventory` を作成してください。"
    lines = [
        "| ID | 観点 | 記載状況 | レポート上の結論 | 関連評価 | 理由 |",
        "|---|---|---|---|---|---|",
    ]
    for row in inventory:
        cid = row.get("conclusion_id") or "-"
        topic = row.get("topic") or "-"
        presence = row.get("presence") or "-"
        conclusion = str(row.get("stated_conclusion") or "").replace("\n", " ")
        linked = ", ".join(row.get("assessment_ids") or []) or "-"
        reason = str(row.get("reason") or "").replace("\n", " ")
        lines.append(f"| {cid} | {topic} | {presence} | {conclusion} | {linked} | {reason} |")
    return "\n".join(lines)


def render_consistency(data: object) -> str:
    consistency = (data or {}).get("consistency_assessments", [])
    if not consistency:
        return "主要結論間の整合性評価がありません。`claim_assessments.json` の `consistency_assessments` を作成してください。"
    lines = [
        "| ID | 関連結論 | 判定 | 評価理由 | 修正案 |",
        "|---|---|---|---|---|",
    ]
    for row in consistency:
        cid = row.get("consistency_id") or "-"
        related = ", ".join(row.get("related_conclusion_ids") or []) or "-"
        verdict = row.get("consistency_verdict") or "-"
        reason = str(row.get("reason") or "").replace("\n", " ")
        suggested = str(row.get("suggested_revision") or "").replace("\n", " ")
        lines.append(f"| {cid} | {related} | {verdict} | {reason} | {suggested} |")
    return "\n".join(lines)


def render_recommendations(data: object) -> str:
    assessments = (data or {}).get("recommendation_assessments", [])
    if not assessments:
        return (
            "推奨対策の対応評価JSONは提供されていません。推奨対策レビューを実施した場合は、"
            "`claim_assessments.json` 内の `recommendation_assessments` を指定してください。"
        )
    lines = [
        "| ID | 推奨対策 | 対応する所見 | 評価 | 評価理由 |",
        "|---|---|---|---|---|",
    ]
    for a in assessments:
        aid = a.get("recommendation_id") or a.get("id") or "-"
        rec = str(
            a.get("recommendation_text") or a.get("recommendation") or ""
        ).replace("\n", " ")
        linked = ", ".join(
            a.get("linked_finding_ids")
            or a.get("related_claim_ids")
            or a.get("mapped_claim_ids")
            or []
        )
        verdict = a.get("review_verdict") or "-"
        reason = str(
            a.get("review_rationale") or a.get("rationale") or a.get("reason") or ""
        ).replace("\n", " ")
        lines.append(f"| {aid} | {rec} | {linked or '-'} | {verdict} | {reason} |")
    return "\n".join(lines)


def render_mechanical(data: object) -> str:
    checks = (data or {}).get("checks", data if isinstance(data, list) else [])
    if not checks:
        return "機械チェック結果は提供されていません。"
    lines = ["| signal | status | summary |", "|---|---|---|"]
    for c in checks:
        key = c.get("key") or c.get("signal") or "-"
        status = c.get("status") or c.get("signal_status") or "-"
        summary = str(
            c.get("message") or c.get("summary") or c.get("detail") or ""
        ).replace("\n", " ")
        lines.append(f"| {key} | {status} | {summary} |")
    return "\n".join(lines)


def render_checklist_appendix(results: list[dict], items: list[dict]) -> str:
    item_by_id = {i["id"]: i for i in items}
    lines = [
        "| ID | 区分 | 評価対象 | 判定 | 根拠・理由 | 項目 |",
        "|---|---|---|---|---|---|",
    ]
    for r in sorted(results, key=lambda row: result_id(row) or ""):
        rid = result_id(r) or "-"
        item = item_by_id.get(rid, {})
        level = item.get("requirement_level") or item.get("level") or "-"
        applies = item.get("applies_to") or "-"
        verdict = "out_of_scope" if r.get("evaluation_scope") == "out_of_scope" else r.get("verdict")
        rationale = result_rationale(r).replace("\n", " ")
        text = str(item.get("text") or "").replace("\n", " ")
        lines.append(f"| {rid} | {level} | {applies} | {verdict} | {rationale} | {text} |")
    return "\n".join(lines)


def render_unknown_confirmations(results: list[dict], items: list[dict]) -> str:
    """List every unknown-verdict checklist row directly.

    check_issues.py requires a matching external_confirmation issue for each
    of these, so `section_or_empty(issues, {"external_confirmation"})` already
    lists them — but only in the issue's own wording. This section instead
    quotes the checklist item and its `external_confirmation_needed` text
    verbatim from results.json, so a reader can see the unknown-verdict count
    from the summary line accounted for one by one, independent of how the
    issue was phrased.
    """
    item_by_id = {i["id"]: i for i in items}
    rows = [r for r in results if r.get("verdict") == "unknown"]
    if not rows:
        return "unknown 判定の項目はありません。"
    lines = []
    for r in sorted(rows, key=lambda row: result_id(row) or ""):
        rid = result_id(r) or "-"
        text = str(item_by_id.get(rid, {}).get("text") or "").replace("\n", " ")
        needed = str(r.get("external_confirmation_needed") or "").replace("\n", " ")
        lines.append(f"- {rid}（{text}）: {needed or '確認すべき資料が未記載です'}")
    return "\n".join(lines)


def render(metadata: object, issues: list[dict], summary: dict, results: list[dict],
           items: list[dict], assessments: object, mechanical: object) -> str:
    metadata = metadata if isinstance(metadata, dict) else {}
    docs = (metadata or {}).get("documents", [])
    if docs:
        target_lines = [
            f"- `{d.get('document_id', '-')}`: {d.get('source_basename') or d.get('source_path') or '-'}"
            for d in docs
        ]
    elif metadata.get("report_path"):
        target_lines = [
            f"- 対象報告書: `{metadata.get('report_path')}`",
            f"- レビュー種別: {metadata.get('review_mode', metadata.get('mode', '-'))}",
            f"- 実行ID: {metadata.get('run_id', '-')}",
            f"- モデル/Agent: {metadata.get('model', metadata.get('agent', '-'))}",
        ]
    else:
        target_lines = ["- レビュー対象メタデータは提供されていません。"]

    summary_md = to_markdown(summary).strip()
    return "\n\n".join([
        FIXED_HEADINGS[0],
        FIXED_HEADINGS[1],
        "\n".join(target_lines),
        FIXED_HEADINGS[2],
        summary_md,
        FIXED_HEADINGS[3],
        section_or_empty(issues, {"quality_defect"}, {"critical", "high"}),
        FIXED_HEADINGS[4],
        "\n\n".join([
            "### 4.1 主要結論の棚卸し",
            render_inventory(assessments if isinstance(assessments, dict) else {}),
            "### 4.2 主要結論間の整合性",
            render_consistency(assessments if isinstance(assessments, dict) else {}),
            "### 4.3 各主要結論の妥当性",
            render_assessments(assessments),
        ]),
        FIXED_HEADINGS[5],
        render_recommendations(assessments if isinstance(assessments, dict) else {}),
        FIXED_HEADINGS[6],
        section_or_empty(issues, {"quality_defect"}, {"medium", "low", "info"}),
        FIXED_HEADINGS[7],
        render_mechanical(mechanical),
        FIXED_HEADINGS[8],
        "\n\n".join([
            "### 8.1 指摘としての外部確認事項",
            section_or_empty(issues, {"external_confirmation"}),
            "### 8.2 unknown 判定の項目（要確認資料）",
            render_unknown_confirmations(results, items),
        ]),
        FIXED_HEADINGS[9],
        section_or_empty(issues, {"optional_enhancement"}),
        FIXED_HEADINGS[10],
        "\n".join([
            "- 報告書に記載のないログ・証拠の正しさ、ベンダーが実際に行った作業内容、原始証拠の真正性は検証していません。",
            "- 未提供の別紙・合意文書に依存する項目は、報告書外の確認事項として扱っています。",
            "- 脅威情報の外部照会は、ユーザーが明示的に指示した場合を除き実施していません。",
            "- 本レビューは一次レビュー支援であり、人間の最終判断を代替しません。",
        ]),
        FIXED_HEADINGS[11],
        render_checklist_appendix(results, items),
        "",
    ])


def main() -> int:
    review_io.require_via_review_status("render_review.py")
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--issues", required=True, type=Path)
    ap.add_argument("--summary", required=True, type=Path)
    ap.add_argument("--results", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--skill-dir", type=Path,
                    default=Path(__file__).resolve().parent.parent)
    ap.add_argument(
        "--mode",
        choices=("customer", "reporter", "both", "auto"),
        default="auto",
        help="Checklist set expected in results.json",
    )
    ap.add_argument("--metadata", type=Path)
    ap.add_argument("--claim-assessments", required=True, type=Path)
    ap.add_argument("--mechanical", type=Path)
    args = ap.parse_args()

    issues_data = load_json(args.issues, {})
    issues = issues_data.get("issues", issues_data if isinstance(issues_data, list) else [])
    summary = load_json(args.summary, {})
    results_data = load_json(args.results, {})
    results = results_data.get("results", results_data if isinstance(results_data, list) else [])
    metadata = load_json(args.metadata, {})
    assessments = load_json(args.claim_assessments, {})
    if not (isinstance(assessments, dict) and assessments.get("claim_assessments")):
        print("error: claim_assessments.json with claim_assessments is required", file=sys.stderr)
        return 1
    mechanical = load_json(args.mechanical, {})
    mode = infer_mode(results, args.mode)
    items = load_checklist_items(args.skill_dir, mode)

    text = render(metadata, issues, summary, results, items, assessments, mechanical)
    review_io.atomic_write_text(args.out, text)
    print(f"rendered review: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
